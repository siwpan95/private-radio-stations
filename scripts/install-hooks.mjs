// 安装 git hooks（幂等）：pre-commit = 快速门禁，pre-push = 全量门禁。
// 由根 package.json 的 postinstall 自动调用，也可手动：node scripts/install-hooks.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')

let gitDir = path.join(ROOT, '.git')
try {
  const out = execFileSync('git', ['-C', ROOT, 'rev-parse', '--git-dir'], { encoding: 'utf8' }).trim()
  gitDir = path.isAbsolute(out) ? out : path.join(ROOT, out)
} catch {
  console.log('[hooks] no git repo, skip')
  process.exit(0)
}
const hooksDir = path.join(gitDir, 'hooks')
if (!fs.existsSync(hooksDir)) {
  console.log('[hooks] hooks dir missing, skip')
  process.exit(0)
}

const SHEBANG = '#!/bin/sh'
const HOOKS = {
  'pre-commit': [
    SHEBANG,
    '# auto-generated by scripts/install-hooks.mjs',
    'node scripts/check.mjs --fast',
    'exit $?',
  ].join('\n'),
  'pre-push': [
    SHEBANG,
    '# auto-generated by scripts/install-hooks.mjs',
    '# 全量门禁（冒烟需两服务运行，手动执行 npm run smoke:video / smoke:radio）',
    'node scripts/check.mjs',
    'exit $?',
  ].join('\n'),
}

for (const [name, body] of Object.entries(HOOKS)) {
  const p = path.join(hooksDir, name)
  fs.writeFileSync(p, body + '\n')
  try { fs.chmodSync(p, 0o755) } catch { /* Windows 无需执行位 */ }
  console.log('[hooks] installed ' + p)
}
