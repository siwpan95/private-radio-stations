# -*- coding: utf-8 -*-
"""Generate start-radio.bat (CRLF, pure ASCII) for the Node.js relay radio.

Mirrors deepseek-harness' gen_start_bat.py approach: it brings up the local
npm mirror proxy (which works around Node's undici stalling on large tarballs
on this machine), waits for it to be ready, installs dependencies through it,
then launches the app with `node src/index.js`.

Run:  python gen_start_bat.py   ->   produces start-radio.bat (edit-proof: all
content is generated, CRLF + ASCII).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PY = r"F:\Python314\python.exe"
PROXY_PORT = 8899   # 与 npm_local_mirror.py 的默认端口保持一致（NPM_PROXY_PORT 环境变量默认 8899）

BAT = r"""@echo off
REM Private Radio Stations - Node.js launcher (generated by gen_start_bat.py)
setlocal
cd /d "__HERE__"
set NODE_OPTIONS=
set PORT=8000
set PROXY_PORT=__PROXY_PORT__
set NPM_PROXY_PORT=%PROXY_PORT%

REM --- start local npm mirror proxy if not already listening ---
curl -s -o nul -m 2 http://127.0.0.1:%PROXY_PORT%/ >nul 2>&1
if errorlevel 1 (
  start "" /b "__PY__" npm_local_mirror.py
)

REM --- wait for proxy (max 30s) ---
set /a n=0
:waitproxy
curl -s -o nul -m 2 http://127.0.0.1:%PROXY_PORT%/ >nul 2>&1
if not errorlevel 1 goto proxyok
set /a n+=1
if %n%==30 goto proxyfail
timeout /t 1 >nul
goto waitproxy
:proxyok

REM --- install deps through proxy if missing ---
if not exist node_modules (
  echo [start-radio] installing dependencies via mirror proxy...
  npm install --no-audit --no-fund --registry=http://127.0.0.1:%PROXY_PORT%
)

echo [start-radio] starting relay radio on http://localhost:8000
node src/index.js
goto end

:proxyfail
echo [start-radio] mirror proxy unavailable; installing without proxy
if not exist node_modules ( npm install --no-audit --no-fund )
node src/index.js

:end
endlocal
"""

out = os.path.join(HERE, "start-radio.bat")
with open(out, "w", encoding="utf-8", newline="\r\n") as f:
    f.write(BAT.replace("__HERE__", HERE).replace("__PY__", PY).replace("__PROXY_PORT__", str(PROXY_PORT)))
print("wrote", out)
